  corrupt.records.marks.find(m => m.examId === exam.id && m.studentId === pub.ownerId)!.marks = 95;
  assert.throws(() => assertYearIntegrity(requested, corrupt), /locked/);
  schoolYearWorkspaceSchema.parse(next);
