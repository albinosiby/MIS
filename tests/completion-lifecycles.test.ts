  assert.equal(next.records.marks.find(m => m.examId === exam.id && m.studentId === pub.ownerId)?.marks, 82);
  assert.throws(() => decideResultReview(next, admin, { id: review.id, decision: "approved", note: "Repeated decision should fail" }), /undecided/);
  assert.throws(() => requestResultReview(y, parent, { publicationId: pub.id, subjectId: subject.id, proposedMarks: 90, reason: "Family direct mark proposal" }), /allocated/);
  assert.throws(() => requestResultReview(y, teacher, { publicationId: pub.id, subjectId: subject.id, proposedMarks: 101, reason: "Above configured maximum" }), /maximum/);
