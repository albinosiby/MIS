test("timetable publication preserves snapshots and never auto-publishes substitutions", () => {
  let y = createWorkspace().years[0];
  y.records.substitutions = [];
  y = publishTimetable(y, admin);
  const snapshot = structuredClone(y.workflows.timetableVersions[0]);
  assert.throws(() => publishTimetable(y, admin), /already/);
  const slot = y.records.slots[0];
  const changed = putRecord(y, "slots", { ...slot, room: y.records.rooms.find(r => r.name !== slot.room)?.name ?? slot.room });
  assert.deepEqual(changed.workflows.timetableVersions[0], snapshot);
  if (changed.records.slots[0].room !== slot.room)
    assert.equal(changed.records.slots[0].status, "draft");
  assert.throws(() => publishTimetable(y, parent), /Administrator/);
  const corrupt = structuredClone(y);
  corrupt.workflows.timetableVersions[0].slots[0].teacherName = "Rewritten teacher";
  assert.throws(() => assertYearIntegrity(y, corrupt), /history/);
  const root = createWorkspace();
  root.years[0] = changed;
  const projection = projectCloudWorkspace(root, parent);
  const visible = projection.years[0].records.slots.find(s => s.id === slot.id);
  if (visible)
    assert.equal(visible.room, slot.room);
});
test("substitutions require independent approval, explicit publication and retain cancellation audit", () => {
  let y = createWorkspace().years[0];
  y.records.substitutions = [];
  y.records.leaves = [];
  const slot = y.records.slots[0];
  y.records.slots = [{ ...slot, status: "published" }];
  const teacher = { ...testAccounts.find(a => a.role === "teacher")!, personId: slot.staffId }, sub = y.setup.staff.find(s => s.id !== slot.staffId)!;
  const date = academicWeekdayDate(y.setup.calendar.year, slot.weekday);
  y = requestSubstitution(y, teacher, { slotId: slot.id, date, substituteStaffId: sub.id, reason: "Teacher training absence cover" });
  const id = y.workflows.substitutionReviews.at(-1)!.id;
  assert.throws(() => decideSubstitution(y, admin, { id, decision: "published", note: "Publication before approval" }), /Invalid/);
  assert.throws(() => decideSubstitution(y, { ...admin, id: teacher.id }, { id, decision: "approved", note: "Requester attempts self approval" }), /separate/);
  const approved = decideSubstitution(y, reviewer, { id, decision: "approved", note: "Cover teacher availability reviewed" });
  assert.equal(publishTimetable(approved, admin).records.substitutions.length, 0);
  const published = decideSubstitution(approved, admin, { id, decision: "published", note: "Published approved teacher cover" });
  assert.equal(published.records.substitutions.length, 1);
  const cancelled = decideSubstitution(published, admin, { id, decision: "cancelled", note: "Original teacher is available again" });
  assert.equal(cancelled.records.substitutions.length, 0);
  assert.equal(cancelled.workflows.substitutionReviews.at(-1)?.decisions.length, 3);
  assertYearIntegrity(published, cancelled);
  assert.throws(() => decideSubstitution(cancelled, admin, { id, decision: "published", note: "Attempt to reopen cancelled cover" }), /Invalid/);
  assert.throws(() => requestSubstitution(y, parent, { slotId: slot.id, date, substituteStaffId: sub.id, reason: "Unauthorized request by guardian" }), /permitted/);
});
